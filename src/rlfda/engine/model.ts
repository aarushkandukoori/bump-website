/**
 * The integrated cardiac model.
 *
 * Couples the four sub-models into a single hybrid system:
 *
 *   conduction (discrete events)  ->  chamber activation
 *   activation + autonomic + drug ->  circulation (continuous ODE)
 *   circulation                   ->  arterial pressure
 *   arterial pressure             ->  baroreflex  ->  autonomic state
 *   dosing commands               ->  pharmacokinetics -> drug effect
 *
 * Integration scheme
 * ------------------
 * The eight circulation volumes are advanced with classical fixed-step
 * fourth-order Runge-Kutta. The activation functions are evaluated at each
 * Runge-Kutta stage time rather than being frozen across the step, because
 * chamber elastance is the fastest-varying quantity in the system and
 * freezing it would dominate the truncation error.
 *
 * The autonomic effector states and every pharmacokinetic compartment are
 * linear first-order systems and are advanced separately: the drug
 * compartments with their exact exponential solution, the reflex effectors
 * with a matched first-order update. Splitting the stiff-but-linear slow
 * states out of the Runge-Kutta loop is both faster and more accurate than
 * folding them in.
 *
 * The default step of 1 ms is more than an order of magnitude below the
 * fastest time constant in the system (roughly 7 ms for left ventricular
 * ejection through the aortic valve at peak elastance). The solution
 * verification study in the credibility record demonstrates convergence.
 */


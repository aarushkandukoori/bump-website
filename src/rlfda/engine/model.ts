export interface RespirationParams {
  /** Breaths per minute. */
  rate: number;
  /** End-expiratory intrathoracic pressure, mmHg. */
  pEndExpiratory: number;
  /** Inspiratory swing, mmHg (positive number, subtracted at inspiration). */
  swing: number;
}

export const BASELINE_RESPIRATION: RespirationParams = {
  rate: 14,
  pEndExpiratory: -4,
  swing: 3,
};

